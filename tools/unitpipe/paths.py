"""Where the figure pipeline reads and writes (docs/systems/figure-pipeline.md).

- code: tools/unitpipe/ (this folder), versioned;
- sources: assets/tripo/<army>/<model>/ (git-ignored; tools/unitpipe/sources.json lists them by hash),
  or the folder in UNITPIPE_ASSETS;
- work: output/unitpipe/<pipeline>/ (git-ignored): Blender files, frames, logs, check results;
- published: output/figures/<figure>/ (git-ignored): GLBs, the clip table, videos, the preview page;
- the registry: data/figures/index.json (committed, generated by registry.py).
"""
import os
from pathlib import Path

CODE = Path(__file__).resolve().parent
REPO = CODE.parent.parent
# overrides are made absolute: the scripts change folder, so a relative path would move under them
ASSETS = Path(os.environ.get('UNITPIPE_ASSETS', REPO / 'assets' / 'tripo')).expanduser().resolve()
OUTPUT = Path(os.environ.get('UNITPIPE_OUTPUT', REPO / 'output')).expanduser().resolve()
REGISTRY = REPO / 'data' / 'figures' / 'index.json'


def source(army, model):
    """The folder holding one Tripo export (its .fbx and the .fbm texture folder)."""
    return ASSETS / army / model


def work(pipeline):
    """The work folder of a pipeline (created)."""
    d = OUTPUT / 'unitpipe' / pipeline
    d.mkdir(parents=True, exist_ok=True)
    return d


def published(figure):
    """The published folder of a figure (created)."""
    d = OUTPUT / 'figures' / figure
    d.mkdir(parents=True, exist_ok=True)
    return d


if __name__ == '__main__':      # for the shell scripts: python3 paths.py work <pipeline> | published <figure>
    import sys
    kind, arg = sys.argv[1:3]
    print({'work': work, 'published': published}[kind](arg))
