# Export the stylized foliage .blend files to one JS data file the prototypes
# can load from file:// (no server). Keeps the artist's custom (spherical)
# normals and UV0; textures are NOT used (they were never shipped) — our
# painterly shader + generated dab texture replace them.
#
# Usage (from rts/):
#   blender -b assets/painted-foliage/Trees.blend --python tools/blend-to-js.py -- trees
#   blender -b assets/painted-foliage/FilesPlants.blend --python tools/blend-to-js.py -- plants
#
# Per-vertex role ids (shared with the shader):
#   0 foliage geometry   2 bark   13 foliage CARD (alpha from dab texture via UV0)
#   12 flower head (top of flower models)   14 reed / grass blade
import bpy, json, sys, os, random

tag = sys.argv[-1]
out_dir = os.path.join(os.path.dirname(bpy.data.filepath), '..', '..', 'prototypes')
out = os.path.abspath(os.path.join(out_dir, f'foliage-{tag}.data.js'))

def role_for(obj, poly, uv_layer):
    name = obj.name
    mat = obj.material_slots[poly.material_index].material.name.lower() if obj.material_slots and obj.material_slots[poly.material_index].material else ''
    if 'trunk' in mat: return 2
    if name.startswith(('S_Grass', 'S_Cattail')): return 14
    if uv_layer is not None:
        us = [uv_layer.data[i].uv for i in poly.loop_indices]
        ex = max(u.x for u in us) - min(u.x for u in us)
        ey = max(u.y for u in us) - min(u.y for u in us)
        if len(poly.vertices) == 4 and ex > 0.4 and ey > 0.4: return 13      # a leaf card
    return 0

data = {}
for obj in bpy.data.objects:
    if obj.type != 'MESH' or not obj.name.startswith('S_'): continue
    me = obj.data
    me.calc_loop_triangles()
    M3 = obj.matrix_world.to_3x3()          # rotation + scale (FBX imports are rotated/scaled)
    N3 = M3.inverted().transposed()
    uvl = me.uv_layers[0] if me.uv_layers else None
    rng = random.Random(hash(obj.name) & 0xffff)
    card_seed = {}
    zs_w = [(M3 @ v.co).z for v in me.vertices]; zmin, zmax = min(zs_w), max(zs_w)
    pos, nrm, uv, role, seed, idx, key = [], [], [], [], [], [], {}
    for tri in me.loop_triangles:
        poly = me.polygons[tri.polygon_index]
        r = role_for(obj, poly, uvl)
        if obj.name.startswith('S_Flowers'):
            if max(((M3 @ me.vertices[v].co).z - zmin) / max(zmax - zmin, 1e-6) for v in poly.vertices) > 0.72: r = 12
        s = card_seed.setdefault(tri.polygon_index, rng.random())
        ids = []
        for li in tri.loops:
            loop = me.loops[li]
            co = M3 @ me.vertices[loop.vertex_index].co
            n = (N3 @ __import__('mathutils').Vector(tri.split_normals[list(tri.loops).index(li)])).normalized()
            u = uvl.data[li].uv if uvl else (0, 0)
            k = (loop.vertex_index, round(n[0], 3), round(n[1], 3), round(n[2], 3), round(u[0], 4), round(u[1], 4), r)
            if k not in key:
                key[k] = len(role)
                # Blender Z-up -> Babylon Y-up (x, z, y)
                pos += [round(co.x, 4), round(co.z, 4), round(co.y, 4)]
                nrm += [round(n[0], 3), round(n[2], 3), round(n[1], 3)]
                uv += [round(u[0], 4), round(u[1], 4)]
                role.append(r); seed.append(round(s, 3))
            ids.append(key[k])
        idx += ids
    xs, ys, zs = pos[0::3], pos[1::3], pos[2::3]
    data[obj.name] = dict(pos=pos, nrm=nrm, uv=uv, role=role, seed=seed, idx=idx,
                          min=[min(xs), min(ys), min(zs)], max=[max(xs), max(ys), max(zs)])
    roles = {x: role.count(x) for x in set(role)}
    print(f"{obj.name:14} verts={len(role):6} tris={len(idx)//3:6} h={max(ys)-min(ys):.2f} roles={roles}")

with open(out, 'w') as f:
    f.write(f'// generated by tools/blend-to-js.py ({tag})\nwindow.FOLIAGE=Object.assign(window.FOLIAGE||{{}},{json.dumps(data, separators=(",", ":"))});\n')
print('wrote', out, os.path.getsize(out) // 1024, 'KB')
