// Converts selected Quaternius OBJ models into one JS data file the prototypes can
// load from file:// (no server needed). Per vertex we keep position + a "role" id
// derived from the OBJ material name; the painterly shader picks colours by role,
// so the pack's own colours are deliberately discarded.
// Usage: node tools/obj-to-js.mjs
import fs from 'node:fs'
import path from 'node:path'

const SRC = new URL('../assets/nature-pack/OBJ/', import.meta.url).pathname
const OUT = new URL('../prototypes/nature-pack.data.js', import.meta.url).pathname

// role ids shared with the shader: 0 foliage, 1 dark foliage, 2 wood, 3 rock,
// 4 birch bark, 5 bark mark, 6 flower warm, 7 flower cool, 8 grain/wheat, 9 berry
const ROLE = {
  Green: 0,
  Leaves: 0,
  DarkGreen: 1,
  Wood: 2,
  LightWood: 2,
  Rock: 3,
  White: 4,
  Black: 5,
  Yellow: 8,
  Orange: 6,
  LightOrange: 6,
  Pink: 6,
  Cyan: 7,
  Berry: 9,
  Mushroom_Top: 6,
  Mushroom_Bottom: 4,
}

const MODELS = [
  ...[1, 2, 3, 4, 5].map(i => `CommonTree_${i}`),
  ...[1, 2, 3, 4, 5].map(i => `BirchTree_${i}`),
  ...[1, 2, 3].map(i => `Willow_${i}`),
  ...[1, 2, 3].map(i => `PineTree_${i}`),
  'Bush_1',
  'Bush_2',
  'BushBerries_1',
  'BushBerries_2',
  ...[1, 2, 3, 4].map(i => `Rock_Moss_${i}`),
  'Rock_1',
  'Rock_2',
  'Grass',
  'Grass_Short',
  'Flowers',
  'Plant_1',
  'Plant_2',
  'Wheat',
  'TreeStump',
  'WoodLog_Moss',
]

function convert(name) {
  const lines = fs.readFileSync(path.join(SRC, name + '.obj'), 'utf8').split('\n')
  const V = []
  const pos = []
  const role = []
  const idx = []
  const key = new Map()
  let cur = 0
  let unknown = new Set()
  for (const l of lines) {
    const p = l.trim().split(/\s+/)
    if (p[0] === 'v') V.push([+p[1], +p[2], +p[3]])
    else if (p[0] === 'usemtl') {
      const m = p[1].replace(/\.\d+$/, '')
      if (!(m in ROLE)) unknown.add(m)
      cur = ROLE[m] ?? 0
    } else if (p[0] === 'f') {
      // weld by (position, role) so the browser can compute SMOOTH normals:
      // faceted low-poly turns into soft painted forms
      const ids = p.slice(1).map(s => {
        const vi = parseInt(s, 10) - 1
        const k = vi * 16 + cur
        if (!key.has(k)) {
          key.set(k, role.length)
          pos.push(...V[vi])
          role.push(cur)
        }
        return key.get(k)
      })
      for (let i = 1; i + 1 < ids.length; i++) idx.push(ids[0], ids[i], ids[i + 1])
    }
  }
  if (unknown.size) console.warn(name, 'unmapped materials:', [...unknown].join(','))
  let min = [1e9, 1e9, 1e9]
  let max = [-1e9, -1e9, -1e9]
  for (let i = 0; i < pos.length; i += 3) {
    for (let a = 0; a < 3; a++) {
      min[a] = Math.min(min[a], pos[i + a])
      max[a] = Math.max(max[a], pos[i + a])
    }
  }
  return { pos: pos.map(v => Math.round(v * 1000) / 1000), role, idx, min, max }
}

const out = {}
for (const m of MODELS) {
  out[m] = convert(m)
  const o = out[m]
  console.log(
    `${m.padEnd(16)} verts=${String(o.role.length).padStart(5)} tris=${String(o.idx.length / 3).padStart(5)} h=${(o.max[1] - o.min[1]).toFixed(2)} w=${(o.max[0] - o.min[0]).toFixed(2)}`,
  )
}
fs.writeFileSync(
  OUT,
  '// generated by tools/obj-to-js.mjs from Quaternius Ultimate Nature (CC0)\nwindow.NATURE=' +
    JSON.stringify(out) +
    ';\n',
)
console.log('wrote', OUT, (fs.statSync(OUT).size / 1024).toFixed(0) + ' KB')
